//! The distribution of W, the LZ78 phrase count of 2^k fair random bits.
//!
//! `counts[i]` is the number of strings (exact tables) or replications
//! (simulated tables) with W = `w_min + i`.  Every table is the output of
//! `examples/lz78_table.rs`:
//!
//! | k | command | total |
//! |---|---|---|
//! | 3 … 5 | `exact k`, every string of 2^k bits | 2^(2^k) |
//! | 6 … 16 | `simulate k 10000 100 7919k` | 10⁶ |
//! | 17 … 22 | `simulate k 1000 100 7919k` | 10⁵ |
//! | 23 … 28 | `simulate k 100 100 7919k` | 10⁴ |
//!
//! A simulation's thread t draws its replications from
//! `Pcg64::new(0x6c7a_3738_7461_626c, 7919k + t)`.

